#!/usr/bin/env node
/**
 * Build the Web half of a bundle that has no bundler of its own.
 *
 * The harness loads a package's browser artifact as a lazy CommonJS factory:
 *
 *   window.__ModuleLoader__.load({ id: '<package name>', factory(require) { … } })
 *
 * and materializes the factory's return value as the package's exports.
 *
 * esbuild cannot emit that wrapper, so the entry keeps the call itself and this
 * script reshapes what esbuild produced around it:
 *
 *   1. bundle `src/client/index.ts` to an IIFE, everything but `external`
 *      inlined — the entry's own `window.__ModuleLoader__.load({ id, factory })`
 *      survives the bundle because nothing can fold it away;
 *   2. rename that inner factory to a plain function (`__yeeFactory`), drop its
 *      registration call, and keep everything before it — the entry's module
 *      scope — beside it;
 *   3. wrap the whole body in the harness's factory, which returns the renamed
 *      factory's result, so `require("react")` inside resolves through the
 *      module table the harness hands in.
 *
 * A factory is not a module, so `"use strict"` moves inside it.
 *
 *   node scripts/build-client.mjs [package-dir]
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { build } from "esbuild";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const packageDir = resolve(process.argv[2] ?? join(repoRoot, "packages", "dsh"));
const pkg = JSON.parse(readFileSync(join(packageDir, "package.json"), "utf8"));

const declaration = pkg.dsh?.client;
if (declaration === undefined) {
	console.log(`build-client: ${pkg.name} declares no dsh.client; nothing to build`);
	process.exit(0);
}

const externals = new Set([...(declaration.external ?? []), ...(declaration.seed ?? [])]);
// React and the cordis runtime are platform seed words of the Web shell even
// when a package does not list them: they are never bundled.
for (const seed of ["react", "react/jsx-runtime", "react-dom", "react-dom/client", "@deepseek-ai/cordis", "zod"]) {
	externals.add(seed);
}

const result = await build({
	entryPoints: [join(packageDir, "src", "client", "index.ts")],
	bundle: true,
	write: false,
	format: "iife",
	platform: "neutral",
	target: "es2022",
	charset: "utf8",
	legalComments: "none",
	sourcemap: false,
	external: [...externals],
	logLevel: "warning",
	define: { "process.env.NODE_ENV": '"production"' },
});

let raw = result.outputFiles[0].text.trim();

// esbuild prefixes the IIFE with a script-level directive and wraps the body in
// `(() => { … })();`. Strictness belongs to the factory, so both go.
const strict = /^["']use strict["'];?\s*/u;
if (strict.test(raw)) raw = raw.replace(strict, "");
const open = raw.indexOf("(() => {");
const close = raw.lastIndexOf("})();");
if (open !== 0 || close < 0) {
	throw new Error("build-client: unexpected esbuild output shape (no IIFE wrapper)");
}
const body = raw.slice(open + "(() => {".length, close);

// `require("x")` already resolves through the factory's parameter: nothing to rewrite,
// but assert that no dynamic require leaked in.
if (/\brequire\((?!["'])/u.test(body)) {
	throw new Error("build-client: dynamic require() in the bundle cannot be resolved by the module table");
}

const banner = `/* ${pkg.name} — browser half. Generated by scripts/build-client.mjs; do not edit. */\n`;

// esbuild has already inlined the entry's own `window.__ModuleLoader__.load(…)`
// call, and that inner factory still returns the module value. Rename it and
// keep the entry as the body; the harness's factory returns its result.
const registration = /window\.__ModuleLoader__\.load\(\{\s*id:\s*"[^"]*",\s*factory\(([\w$]+)\)\s*\{/u;
const match = registration.exec(body);
if (match === null) {
	throw new Error("build-client: the client entry never registers a module factory");
}
let source = body.replace(
	registration,
	(_match, param) => `function __yeeFactory(${param}) {`,
);
if (!source.includes("function __yeeFactory(")) {
	throw new Error("build-client: the client entry never registers a module factory");
}
// The inner registration's closing `});` — the last statement of the entry —
// becomes the renamed function's own `}`. Everything between it and the
// harness's factory wrapper is scaffolding, so the entry is sliced up to the
// closing call and re-closed here.
// The rename replaced the call, so the entry's own last statement is the
// factory body's closing `});`: cut it and re-close as a function.
const closeCall = source.lastIndexOf("});");
if (closeCall < 0) throw new Error("build-client: the entry's registration has no closing `});`");
source = source.slice(0, closeCall);

// Keep the rewritten close on the entry's own indentation level. Blank lines go:
// every line of the injected source must carry its own indentation.
const dedent = (text) => {
	const rows = text.split("\n").filter((row) => row.trim().length > 0);
	const indent = Math.min(...rows.map((row) => /^[ \t]*/u.exec(row)[0].length));
	return rows.map((row) => row.slice(indent)).join("\n");
};
source = dedent(source).replace(/^(?=.)/gmu, "    ");


// The body ends with the renamed factory's closing brace; this wrapper owns
// everything after it.
const injected = source.replace(/\n+$/u, "");
const output = [
	banner,
	"window.__ModuleLoader__.load({",
	`  id: ${JSON.stringify(pkg.name)},`,
	"  factory(require) {",
	'    "use strict";',
	injected,
	"    return __yeeFactory(require);",
	"  },",
	"});",
	"",
].join("\n");

const target = join(packageDir, "client.js");
writeFileSync(target, output);
console.log(`build-client: wrote ${target} (${(output.length / 1024).toFixed(1)} KiB)`);
